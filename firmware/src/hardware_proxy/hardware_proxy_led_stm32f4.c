#include "hardware_proxy/hardware_proxy_led.h"
#include "infrastructure/time_base.h"
#include "main.h"

/* Real STM32F4 implementation of the Hardware Proxy LED/Buzzer contract.
 *
 * Only compiled by the MCU_F4 CubeIDE project, never the host build - same
 * reasoning as hardware_proxy_digital_io_stm32f4.c (HAL types only exist
 * for the ARM toolchain). CMakeLists.txt excludes every "*_stm32f4.c" file
 * from the host build; hardware_proxy_led.c (the host-stub) is used there
 * instead.
 *
 * Unlike hardware_proxy_digital_io_stm32f4.c / hardware_proxy_analog_io_stm32f4.c,
 * this file talks to HAL_GPIO_* directly instead of going through
 * infrastructure/drivers/led.h - that Driver header and its Stub
 * (infrastructure/drivers/led.c) stay a host-only pass-through target,
 * never compiled on real hardware, same as every other Driver Stub in this
 * firmware (CLAUDE.md: "drivers/*.c همچنان Stub"). Real hardware always
 * talks to HAL straight from the *_stm32f4.c Hardware Proxy file, exactly
 * like the Digital I/O real implementation already does.
 *
 * The pin/port names below (LED_GSM_Pin, LED_GSM_GPIO_Port, ...) are not
 * invented here - they come straight from MCU_F4/Core/Inc/main.h,
 * generated by CubeMX from ConnectedCar.ioc / "pins name.txt" (its "led"
 * section: LED_GSM/LED_GPS/LED_SIM/LED_POWER). BUZZER_Pin/BUZZER_GPIO_Port
 * are "pins name.txt"'s "output" section BUZZER entry, same source.
 *
 * HWPROXY_LED_BLINK_SLOW/FAST are not a state a single GPIO write can hold
 * by itself - a pin cannot visibly blink from one HAL_GPIO_WritePin() call.
 * This file turns them into a real periodic toggle using Time Base (the
 * same Non-Blocking, Process()-driven timing pattern every other periodic
 * behavior in this firmware already uses, e.g.
 * hardware_input_management.c's debounce/EMA/Telemetry cadence), not a
 * hardware Timer/PWM peripheral - no Timer channel is configured for any
 * LED in the current CubeMX project, and introducing one would be a real
 * hardware/CubeMX decision, not a software-only fix. HWProxy_SetLed() only
 * records the desired state (and, for ON/OFF, writes the pin once);
 * HWProxy_Led_Process() - called every Super Loop lap from
 * system_management.c's System_Process() - is what actually toggles a
 * blinking pin at the fixed rate below. */

#define LED_BLINK_SLOW_HALF_PERIOD_MS 500u /* -> ~1s full on/off cycle - placeholder rate, adjust once real hardware is on the bench */
#define LED_BLINK_FAST_HALF_PERIOD_MS 150u /* -> ~300ms full on/off cycle */

typedef struct {
    GPIO_TypeDef* port;
    uint16_t      pin;
} LedMapping;

static const LedMapping LED_MAP[] = {
    [HWPROXY_LED_GSM]   = { LED_GSM_GPIO_Port,   LED_GSM_Pin   },
    [HWPROXY_LED_GPS]   = { LED_GPS_GPIO_Port,   LED_GPS_Pin   },
    [HWPROXY_LED_SIM]   = { LED_SIM_GPIO_Port,   LED_SIM_Pin   },
    [HWPROXY_LED_POWER] = { LED_POWER_GPIO_Port, LED_POWER_Pin },
};
#define NUM_LEDS (sizeof(LED_MAP) / sizeof(LED_MAP[0]))

static HWProxy_LedState s_desired_state[NUM_LEDS];
static bool              s_blink_phase_on[NUM_LEDS]; /* current physical output while a Blink state is active */
static TimeTick          s_last_toggle_tick[NUM_LEDS];

static void write_pin(HWProxy_LedId id, bool on) {
    HAL_GPIO_WritePin(LED_MAP[id].port, LED_MAP[id].pin, on ? GPIO_PIN_SET : GPIO_PIN_RESET);
}

void HWProxy_SetLed(HWProxy_LedId id, HWProxy_LedState state) {
    if ((uint32_t)id >= NUM_LEDS) {
        return; /* defensive - Management-side callers already only ever use the 4 known ids */
    }

    s_desired_state[id] = state;

    switch (state) {
        case HWPROXY_LED_OFF:
            write_pin(id, false);
            break;
        case HWPROXY_LED_ON:
            write_pin(id, true);
            break;
        case HWPROXY_LED_BLINK_SLOW:
        case HWPROXY_LED_BLINK_FAST:
            /* Start the blink phase ON immediately (visible right away,
             * same instant-feedback behavior ON/OFF above already give)
             * and reset the toggle timer - HWProxy_Led_Process() takes
             * over the actual toggling from here, every Super Loop lap. */
            s_blink_phase_on[id]   = true;
            s_last_toggle_tick[id] = Time_GetTick();
            write_pin(id, true);
            break;
    }
}

void HWProxy_Led_Process(void) {
    for (uint32_t i = 0; i < NUM_LEDS; i++) {
        uint32_t half_period_ms;

        if (s_desired_state[i] == HWPROXY_LED_BLINK_SLOW) {
            half_period_ms = LED_BLINK_SLOW_HALF_PERIOD_MS;
        } else if (s_desired_state[i] == HWPROXY_LED_BLINK_FAST) {
            half_period_ms = LED_BLINK_FAST_HALF_PERIOD_MS;
        } else {
            continue; /* OFF/ON - fully handled already by HWProxy_SetLed(), nothing to toggle */
        }

        if (!Time_Elapsed(s_last_toggle_tick[i], half_period_ms)) {
            continue;
        }

        s_blink_phase_on[i]   = !s_blink_phase_on[i];
        s_last_toggle_tick[i] = Time_GetTick();
        write_pin((HWProxy_LedId)i, s_blink_phase_on[i]);
    }
}

void HWProxy_SetBuzzer(bool on) {
    HAL_GPIO_WritePin(BUZZER_GPIO_Port, BUZZER_Pin, on ? GPIO_PIN_SET : GPIO_PIN_RESET);
}
