#include "hardware_proxy/hardware_proxy_digital_io.h"
#include "main.h"

/* Real STM32F4 implementation of the Hardware Proxy digital I/O contract.
 *
 * This file is only meant to be compiled by the MCU_F4 CubeIDE project,
 * never by the host (PC) build. HAL_GPIO_ReadPin/HAL_GPIO_WritePin and
 * the GPIO_TypeDef type only exist for the ARM/STM32 toolchain (via
 * stm32f4xx_hal.h, pulled in transitively through "main.h" here); plain
 * host gcc cannot compile this. CMakeLists.txt excludes every
 * "*_stm32f4.c" file from the host build for exactly this reason, and
 * hardware_proxy_digital_io.c (the host-stub, same function names) is
 * used there instead. Full explanation:
 * docs/03-infrastructure-contracts/target-integration.md and
 * docs/03-infrastructure-contracts/hardware-proxy.md section 7.
 *
 * The pin/port names below (ACC_Pin, ACC_GPIO_Port, ...) are not
 * invented here - they come straight from MCU_F4/Core/Inc/main.h,
 * generated by CubeMX from ConnectedCar.ioc / "pins name.txt". Line
 * numbers must stay in sync with the placeholder mapping in
 * hardware_input_management.c (DIGITAL_CONFIG: ACC=0, DOOR=1, SHOCK=2).
 * Line 3 (reserve_input) is wired here ahead of time even though no
 * DigitalInputId uses it yet, so it is ready the moment Hardware Input
 * Management assigns its 4th channel. */

typedef struct {
    GPIO_TypeDef* port;
    uint16_t      pin;
} LineMapping;

static const LineMapping LINE_MAP[] = {
    { ACC_GPIO_Port,           ACC_Pin           }, /* line 0 */
    { DOOR_GPIO_Port,          DOOR_Pin          }, /* line 1 */
    { SHOCK_GPIO_Port,         SHOCK_Pin         }, /* line 2 */
    { reserve_input_GPIO_Port, reserve_input_Pin }, /* line 3 - not assigned to a DigitalInputId yet */
};
#define LINE_MAP_SIZE (sizeof(LINE_MAP) / sizeof(LINE_MAP[0]))

HWProxy_Result HWProxy_DigitalIo_Init(void) {
    /* GPIO clock enable and pin mode configuration are already done by
     * CubeMX-generated MX_GPIO_Init(), called from Core/Src/main.c
     * before Firmware_Main() runs - nothing left to do here. */
    return HWPROXY_OK;
}

HWProxy_Result HWProxy_ReadDigitalLine(HWProxy_DigitalLine line, bool* value) {
    if (line < 0 || (uint32_t)line >= LINE_MAP_SIZE || value == NULL) {
        return HWPROXY_INVALID;
    }

    *value = (HAL_GPIO_ReadPin(LINE_MAP[line].port, LINE_MAP[line].pin) == GPIO_PIN_SET);
    return HWPROXY_OK;
}

HWProxy_Result HWProxy_WriteDigitalLine(HWProxy_DigitalLine line, bool value) {
    if (line < 0 || (uint32_t)line >= LINE_MAP_SIZE) {
        return HWPROXY_INVALID;
    }

    HAL_GPIO_WritePin(LINE_MAP[line].port, LINE_MAP[line].pin, value ? GPIO_PIN_SET : GPIO_PIN_RESET);
    return HWPROXY_OK;
}
